let activeProject = "cheong";
let statusTimer;

const status = document.querySelector(".copy-status");
const labLabel = document.querySelector("[data-lab-label]");
const labTitle = document.querySelector("[data-lab-title]");
const labResume = document.querySelector("[data-lab-resume]");
const flowSteps = document.querySelector("[data-flow-steps]");
const flowTitle = document.querySelector("[data-flow-title]");
const flowDescription = document.querySelector("[data-flow-description]");

function showStatus(message) {
  status.textContent = message;
  status.classList.add("is-visible");
  window.clearTimeout(statusTimer);
  statusTimer = window.setTimeout(() => status.classList.remove("is-visible"), 1800);
}

async function copyText(text) {
  try {
    await navigator.clipboard.writeText(text);
  } catch {
    const textarea = document.createElement("textarea");
    textarea.value = text;
    textarea.setAttribute("readonly", "");
    textarea.style.position = "fixed";
    textarea.style.opacity = "0";
    document.body.appendChild(textarea);
    textarea.select();
    document.execCommand("copy");
    textarea.remove();
  }
  showStatus("문구를 복사했습니다.");
}

function selectFlowStep(index) {
  const project = projects[activeProject];
  const step = project.steps[index];
  flowTitle.textContent = step[0];
  flowDescription.textContent = step[1];
  flowSteps.querySelectorAll("button").forEach((button, buttonIndex) => {
    button.classList.toggle("is-active", buttonIndex === index);
    button.setAttribute("aria-pressed", String(buttonIndex === index));
  });
}

function renderLab(projectKey) {
  activeProject = projectKey;
  const project = projects[projectKey];
  labLabel.textContent = project.label;
  labTitle.textContent = project.title;
  labResume.textContent = project.resume;
  flowSteps.replaceChildren();

  project.steps.forEach((step, index) => {
    const button = document.createElement("button");
    button.type = "button";
    button.textContent = step[0];
    button.addEventListener("click", () => selectFlowStep(index));
    flowSteps.appendChild(button);
  });

  document.querySelectorAll("[data-lab-project]").forEach((tab) => {
    tab.setAttribute("aria-selected", String(tab.dataset.labProject === projectKey));
  });
  selectFlowStep(0);
}

document.querySelectorAll("[data-lab-project]").forEach((tab) => {
  tab.addEventListener("click", () => renderLab(tab.dataset.labProject));
});

document.querySelectorAll(".copy-button").forEach((button) => {
  button.addEventListener("click", () => copyText(projects[button.dataset.project][button.dataset.copySource]));
});

document.querySelectorAll("[data-lab-copy]").forEach((button) => {
  button.addEventListener("click", () => copyText(projects[activeProject][button.dataset.copySource]));
});

renderLab(activeProject);
